/** One JSON-RPC round trip. Injected by the tests, which never touch a network. */
export type RpcFn = (method: string, params: readonly unknown[]) => Promise<unknown>;

const URL_LIKE = /\bhttps?:\/\/[^\s"'\\]*/gi;

/** Every absolute URL replaced by `<rpc>`: an operator endpoint usually *is* the credential. */
export function redactUrls(value: string): string {
  return value.replace(URL_LIKE, "<rpc>");
}

/** A `fetch`-backed `RpcFn` for one endpoint. Nothing else in this file knows the URL. */
export function httpRpc(url: string, timeoutMs = 20_000): RpcFn {
  let id = 0;
  return async (method, params) => {
    id += 1;
    const response = await fetch(url, {
      method: "POST",
      headers: {"content-type": "application/json"},
      body: JSON.stringify({jsonrpc: "2.0", id, method, params}),
      signal: AbortSignal.timeout(timeoutMs),
    });
    if (!response.ok) {
      throw new Error(`${method} answered HTTP ${response.status} ${response.statusText}`);
    }
    const payload = (await response.json()) as {result?: unknown; error?: {message?: unknown}};
    if (payload.error !== undefined && payload.error !== null) {
      throw new Error(`${method} failed: ${String(payload.error.message ?? "no message")}`);
    }
    return payload.result;
  };
}

