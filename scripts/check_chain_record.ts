export const ADDRESS_RE = /^0x[0-9a-fA-F]{40}$/;
const ZERO_ADDRESS = "0x0000000000000000000000000000000000000000";

/** The two `networkIdentity` fields of `config/chains/<id>.json`, as read from disk. */
export type ChainRecordIdentity = {
  /** The record's own `chainId`, so a file named for another chain is caught. */
  chainId: number | null;
  genesisHash: string | null;
  multicall3: string | null;
};

export type CheckInput = {
  chainId: bigint;
  multicall3: string;
  rpc: RpcFn;
  /** Null when no record exists for this chain id; then only the chain is checked. */
  record: ChainRecordIdentity | null;
  /** Display path of the record, for the messages. */
  recordPath: string;
  /** Blocks the head may advance by between the two `eth_blockNumber` reads, before it looks wrong. */
  headSlack?: bigint;
  /** UTC date stamped into the printed fragment. Injected by the tests. */
  today?: string;
};

export type Level = "ok" | "note" | "error";
export type Finding = {code: string; level: Level; message: string};

export type Observed = {
  chainId: bigint | null;
  genesisHash: string | null;
  codeSize: number | null;
  codeHash: string | null;
  headBefore: bigint | null;
  headAfter: bigint | null;
  multicallBlockNumber: bigint | null;
  aggregateBlockNumber: bigint | null;
  aggregateChainId: bigint | null;
};

export type CheckResult = {
  findings: Finding[];
  observed: Observed;
  /** The `networkIdentity` object to paste, or null when the chain could not be read. */
  fragment: string | null;
  ok: boolean;
};

function ok(findings: Finding[], code: string, message: string): void {
  findings.push({code, level: "ok", message});
}
function note(findings: Finding[], code: string, message: string): void {
  findings.push({code, level: "note", message});
}
function bad(findings: Finding[], code: string, message: string): void {
  findings.push({code, level: "error", message});
}

async function quantity(rpc: RpcFn, method: string, params: readonly unknown[]): Promise<bigint> {
  const raw = await rpc(method, params);
  if (typeof raw !== "string" || !/^0x[0-9a-fA-F]+$/.test(raw)) {
    throw new Error(`${method} answered ${JSON.stringify(raw)}, which is not a quantity`);
  }
  return BigInt(raw);
}

function message(error: unknown): string {
  return redactUrls(error instanceof Error ? error.message : String(error));
}

function todayUtc(): string {
  return new Date().toISOString().slice(0, 10);
}

/**
 * Reads the chain, compares it with the record and builds the fragment.
 *
 * Every RPC failure becomes a finding rather than a thrown error, so one unreachable method (an old node
 * without `eth_getCode` at `latest`, say) still leaves the other answers on screen.
 */
export async function checkChainRecord(input: CheckInput): Promise<CheckResult> {
  const findings: Finding[] = [];
  const slack = input.headSlack ?? 8n;
  const observed: Observed = {
    chainId: null,
    genesisHash: null,
    codeSize: null,
    codeHash: null,
    headBefore: null,
    headAfter: null,
    multicallBlockNumber: null,
    aggregateBlockNumber: null,
    aggregateChainId: null,
  };

  if (!ADDRESS_RE.test(input.multicall3)) {
    bad(findings, "C0", `--multicall3 ${JSON.stringify(input.multicall3)} is not an address`);
    return {findings, observed, fragment: null, ok: false};
  }
  const multicall3 = input.multicall3.toLowerCase();
  if (multicall3 === ZERO_ADDRESS) {
    bad(findings, "C0", "--multicall3 is the zero address");
    return {findings, observed, fragment: null, ok: false};
  }

  // 1. chain id
  try {
    observed.chainId = await quantity(input.rpc, "eth_chainId", []);
    if (observed.chainId === input.chainId) {
      ok(findings, "C1", `eth_chainId is ${observed.chainId}, as asked`);
    } else {
      bad(
        findings,
        "C1",
        `eth_chainId is ${observed.chainId} but --chain-id is ${input.chainId}; this endpoint is a ` +
          `different network. Nothing below describes the chain you meant.`,
      );
    }
  } catch (error) {
    bad(findings, "C1", `eth_chainId could not be read: ${message(error)}`);
  }

  // 2. genesis hash
  try {
    const block = await input.rpc("eth_getBlockByNumber", ["0x0", false]);
    const hash = (block as {hash?: unknown} | null)?.hash;
    if (typeof hash !== "string" || !/^0x[0-9a-fA-F]{64}$/.test(hash)) {
      bad(findings, "C2", `the node did not return a block 0 hash (got ${JSON.stringify(hash ?? null)})`);
    } else {
      observed.genesisHash = hash.toLowerCase();
      ok(findings, "C2", `block 0 hash is ${observed.genesisHash}`);
    }
  } catch (error) {
    bad(findings, "C2", `block 0 could not be read: ${message(error)}`);
  }

  // 3. code at the given address
  let hasCode = false;
  try {
    const code = await input.rpc("eth_getCode", [multicall3, "latest"]);
    if (typeof code !== "string" || !/^0x([0-9a-fA-F]{2})*$/.test(code)) {
      bad(findings, "C3", `eth_getCode answered ${JSON.stringify(code)}, which is not bytecode`);
    } else if (code === "0x") {
      bad(
        findings,
        "C3",
        `there is no code at ${multicall3} on chain ${observed.chainId ?? "?"}. Multicall3 is not ` +
          `deployed at that address here, or the address is wrong; do not record it.`,
      );
    } else {
      const bytes = Uint8Array.from(
        (hexBody(code).match(/../g) ?? []).map((pair) => Number.parseInt(pair, 16)),
      );
      hasCode = true;
      observed.codeSize = bytes.length;
      observed.codeHash = keccak256(bytes);
      ok(findings, "C3", `${bytes.length} bytes of code at ${multicall3}, keccak256 ${observed.codeHash}`);
    }
  } catch (error) {
    bad(findings, "C3", `eth_getCode could not be read: ${message(error)}`);
  }

  // 4 to 6. the head window, getBlockNumber() and aggregate3 through the address
  if (hasCode) {
    try {
      observed.headBefore = await quantity(input.rpc, "eth_blockNumber", []);
      const direct = await input.rpc("eth_call", [{to: multicall3, data: GET_BLOCK_NUMBER}, "latest"]);
      if (typeof direct !== "string" || hexBody(direct).length !== 64) {
        bad(findings, "C4", `getBlockNumber() answered ${JSON.stringify(direct)}, not one uint256`);
      } else {
        observed.multicallBlockNumber = BigInt(direct);
      }

      const aggregateCall = encodeAggregate3([
        {target: multicall3, callData: GET_BLOCK_NUMBER},
        {target: multicall3, callData: GET_CHAIN_ID},
      ]);
      const aggregated = await input.rpc("eth_call", [{to: multicall3, data: aggregateCall}, "latest"]);
      observed.headAfter = await quantity(input.rpc, "eth_blockNumber", []);

      if (typeof aggregated !== "string") {
        bad(findings, "C5", `aggregate3 answered ${JSON.stringify(aggregated)}`);
      } else {
        // Null, not `[]`: a decode failure and a well-formed but *empty* `Result[]` are different facts and
        // only the first has already produced a finding above. Defaulting to an empty list made the two
        // indistinguishable, and an empty answer then fell through both branches below - C5 stayed silent
        // and the fragment printed as though Multicall3 had confirmed the chain for two calls it never
        // answered. Every non-null length other than 2 is a failure, zero included.
        let items: AggregateItem[] | null = null;
        try {
          items = decodeAggregate3(aggregated);
        } catch (error) {
          bad(findings, "C5", `aggregate3 did not decode as Result[]: ${message(error)}`);
        }
        if (items !== null && items.length === 2) {
          const [blockItem, chainItem] = items;
          if (!blockItem.success || !chainItem.success) {
            bad(
              findings,
              "C5",
              `aggregate3 reported failure for ${!blockItem.success ? "getBlockNumber()" : "getChainId()"}` +
                `; the contract at ${multicall3} does not behave like Multicall3`,
            );
          } else if (
            hexBody(blockItem.returnData).length !== 64 ||
            hexBody(chainItem.returnData).length !== 64
          ) {
            bad(findings, "C5", "aggregate3 returned items that are not uint256 words");
          } else {
            observed.aggregateBlockNumber = BigInt(blockItem.returnData);
            observed.aggregateChainId = BigInt(chainItem.returnData);
          }
        } else if (items !== null) {
          bad(findings, "C5", `aggregate3 returned ${items.length} results for 2 calls`);
        }
      }
    } catch (error) {
      bad(findings, "C4", `the Multicall3 calls could not be made: ${message(error)}`);
    }

    const before = observed.headBefore;
    const after = observed.headAfter;
    const window = (value: bigint | null, code: string, what: string): void => {
      if (value === null || before === null || after === null) return;
      if (value >= before && value <= after + slack) {
        ok(findings, code, `${what} is ${value}, inside the head window ${before}..${after}`);
      } else {
        bad(
          findings,
          code,
          `${what} is ${value} but eth_blockNumber moved ${before} -> ${after} around the call; the ` +
            `contract at ${multicall3} is not answering for this chain's head`,
        );
      }
    };
    window(observed.multicallBlockNumber, "C4", "getBlockNumber()");
    window(observed.aggregateBlockNumber, "C5", "aggregate3 getBlockNumber()");

    if (observed.aggregateChainId !== null) {
      if (observed.aggregateChainId === input.chainId) {
        ok(findings, "C6", `aggregate3 getChainId() is ${observed.aggregateChainId}, as asked`);
      } else {
        bad(
          findings,
          "C6",
          `aggregate3 getChainId() is ${observed.aggregateChainId} but --chain-id is ${input.chainId}`,
        );
      }
    }
  } else {
    note(findings, "C4", "the Multicall3 calls were skipped: there is no code at that address");
  }

  // 7 to 9. the record on disk
  const record = input.record;
  if (record === null) {
    note(findings, "C7", `${input.recordPath} does not exist; nothing on disk to compare`);
  } else {
    if (record.chainId !== null && BigInt(record.chainId) !== input.chainId) {
      bad(
        findings,
        "C7",
        `${input.recordPath} declares chainId ${record.chainId} but --chain-id is ${input.chainId}`,
      );
    }
    const compare = (code: string, field: string, recorded: string | null, seen: string | null): void => {
      if (recorded === null) {
        note(
          findings,
          code,
          `${input.recordPath} networkIdentity.${field} is null; paste the fragment below once the ` +
            `numbers above look right`,
        );
      } else if (seen === null) {
        note(findings, code, `networkIdentity.${field} is recorded as ${recorded}; the chain was not read`);
      } else if (recorded.toLowerCase() === seen) {
        ok(findings, code, `networkIdentity.${field} matches the chain: ${seen}`);
      } else {
        bad(
          findings,
          code,
          `${input.recordPath} networkIdentity.${field} is ${recorded} but the chain says ${seen}. ` +
            `Do not edit the record to agree with an endpoint you have not vetted: find out which is wrong.`,
        );
      }
    };
    compare("C8", "genesisHash", record.genesisHash, observed.genesisHash);
    compare("C9", "multicall3", record.multicall3, hasCode ? multicall3 : null);
  }

  const fragment =
    observed.genesisHash === null || !hasCode
      ? null
      : [
          `  "networkIdentity": {`,
          `    "genesisHash": "${observed.genesisHash}",`,
          `    "multicall3": "${multicall3}",`,
          `    "source": { "url": null, "date": "${input.today ?? todayUtc()}" }`,
          `  }`,
        ].join("\n");

  return {
    findings,
    observed,
    fragment,
    ok: findings.every((finding) => finding.level !== "error"),
  };
}

