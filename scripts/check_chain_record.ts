// Chain identity and Multicall3 check (SPEC sections 10.1, 10.3 and 15).
//
// The chain record `config/chains/<chainId>.json` carries two facts that only a node can settle:
// `networkIdentity.genesisHash` and `networkIdentity.multicall3`. Both are null until an operator verifies
// them against the live chain, and rule CH4 in `scripts/validate_config.ts` fails any chain record that
// still holds a null in either field once a mainnet manifest exists. This script performs that
// verification and prints the fragment to paste, under those two exact field names.
//
// What it does, in order:
//
//   1. `eth_chainId`                          must equal --chain-id;
//   2. `eth_getBlockByNumber("0x0")`          the genesis hash, compared with the record;
//   3. `eth_getCode(--multicall3)`            must be non-empty; its keccak256 is printed as an identity
//                                             fingerprint the operator can compare across chains;
//   4. `eth_blockNumber`                      the head, read before and after the calls;
//   5. `eth_call getBlockNumber()`            through the given address, must land inside that window;
//   6. `eth_call aggregate3([getBlockNumber(), getChainId()])`
//                                             both items must succeed, the block number must land inside
//                                             the same window and the chain id must equal --chain-id.
//
// Rules this file obeys:
//
//   - No address is hardcoded. The Multicall3 address is an operator argument, taken from the source page
//     on the day (brief ground rule; SPEC section 10.3 does not name one).
//   - Read-only. It never writes `config/chains/<id>.json`; --write is refused with a message.
//   - The RPC URL is a credential (operator endpoints carry the key in the path or the query), so it is
//     replaced by `<rpc>` in every line this script prints, including provider error messages.
//   - Runs under plain `node scripts/check_chain_record.ts` on Node 24 (pinned in .nvmrc) and Node 25:
//     inside the erasable TypeScript subset, no enums, no namespaces, no parameter properties.
//
// Usage:
//   node scripts/check_chain_record.ts --rpc-url <url> --chain-id <id> --multicall3 <address>
//                                      [--config-root <dir>] [--head-slack <blocks>]

