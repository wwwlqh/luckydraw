// ---------------------------------------------------------------------------
// keccak256 (FIPS 202), used for the function selectors and the code hash
// ---------------------------------------------------------------------------
//
// The repository root has no ethers dependency (only the workspace packages do), and a selector copied from
// memory is exactly the kind of unverified constant this script exists to eliminate. So the selectors are
// derived from their signatures here, and `check_chain_record.test.ts` pins the derived values against the
// method identifiers Foundry generates for forge-std's `IMulticall3`.

const MASK64: bigint = (1n << 64n) - 1n;

function rotl64(value: bigint, shift: number): bigint {
  const n = BigInt(shift);
  return ((value << n) | (value >> (64n - n))) & MASK64;
}

/** The 24 round constants, generated by the FIPS 202 Algorithm 5 LFSR rather than tabulated. */
const ROUND_CONSTANTS: readonly bigint[] = (() => {
  const constants: bigint[] = [];
  let lfsr = 0x01;
  for (let round = 0; round < 24; round += 1) {
    let rc = 0n;
    for (let j = 0; j < 7; j += 1) {
      const bit = lfsr & 0x01;
      lfsr = (lfsr & 0x80) !== 0 ? ((lfsr << 1) ^ 0x71) & 0xff : (lfsr << 1) & 0xff;
      if (bit !== 0) rc ^= 1n << BigInt((1 << j) - 1);
    }
    constants.push(rc);
  }
  return constants;
})();

/** The rho rotation offsets paired with the pi lane order, generated from the (x, y) walk of FIPS 202. */
const RHO_PI: readonly {lane: number; shift: number}[] = (() => {
  const steps: {lane: number; shift: number}[] = [];
  let x = 1;
  let y = 0;
  for (let t = 0; t < 24; t += 1) {
    const nextX = y;
    const nextY = (2 * x + 3 * y) % 5;
    x = nextX;
    y = nextY;
    steps.push({lane: x + 5 * y, shift: (((t + 1) * (t + 2)) / 2) % 64});
  }
  return steps;
})();

function keccakF1600(lanes: bigint[]): void {
  for (const rc of ROUND_CONSTANTS) {
    const column: bigint[] = [];
    for (let x = 0; x < 5; x += 1) {
      column.push(lanes[x] ^ lanes[x + 5] ^ lanes[x + 10] ^ lanes[x + 15] ^ lanes[x + 20]);
    }
    for (let x = 0; x < 5; x += 1) {
      const d = column[(x + 4) % 5] ^ rotl64(column[(x + 1) % 5], 1);
      for (let y = 0; y < 25; y += 5) lanes[x + y] ^= d;
    }
    let current = lanes[1];
    for (const step of RHO_PI) {
      const held = lanes[step.lane];
      lanes[step.lane] = rotl64(current, step.shift);
      current = held;
    }
    for (let y = 0; y < 25; y += 5) {
      const row = [lanes[y], lanes[y + 1], lanes[y + 2], lanes[y + 3], lanes[y + 4]];
      for (let x = 0; x < 5; x += 1) {
        lanes[y + x] = row[x] ^ (~row[(x + 1) % 5] & MASK64 & row[(x + 2) % 5]);
      }
    }
    lanes[0] ^= rc;
  }
}

/** keccak256 of a byte string, as `0x`-prefixed lowercase hex. */
export function keccak256(message: Uint8Array): string {
  const RATE = 136;
  const lanes: bigint[] = new Array(25).fill(0n);
  const padded = new Uint8Array(Math.ceil((message.length + 1) / RATE) * RATE);
  padded.set(message);
  padded[message.length] ^= 0x01;
  padded[padded.length - 1] ^= 0x80;
  for (let block = 0; block < padded.length; block += RATE) {
    for (let i = 0; i < RATE; i += 8) {
      let lane = 0n;
      for (let b = 7; b >= 0; b -= 1) lane = (lane << 8n) | BigInt(padded[block + i + b]);
      lanes[i / 8] ^= lane;
    }
    keccakF1600(lanes);
  }
  let out = "0x";
  for (let i = 0; i < 32; i += 1) {
    const byte = Number((lanes[Math.floor(i / 8)] >> BigInt(8 * (i % 8))) & 0xffn);
    out += byte.toString(16).padStart(2, "0");
  }
  return out;
}

/** The 4-byte selector of a Solidity function signature, derived (never remembered). */
export function selectorOf(signature: string): string {
  return keccak256(new TextEncoder().encode(signature)).slice(0, 10);
}

export const GET_BLOCK_NUMBER: string = selectorOf("getBlockNumber()");
export const GET_CHAIN_ID: string = selectorOf("getChainId()");
export const AGGREGATE3: string = selectorOf("aggregate3((address,bool,bytes)[])");

// ---------------------------------------------------------------------------
// Minimal ABI coding for the one call shape this script needs
// ---------------------------------------------------------------------------

function hexBody(value: string): string {
  return value.startsWith("0x") || value.startsWith("0X") ? value.slice(2) : value;
}

function word(value: bigint): string {
  if (value < 0n) throw new Error("only non-negative words are encoded here");
  return value.toString(16).padStart(64, "0");
}

function wordAt(body: string, byteOffset: number): bigint {
  const start = byteOffset * 2;
  const slice = body.slice(start, start + 64);
  if (slice.length !== 64) throw new Error(`the response ends inside word ${byteOffset / 32}`);
  return BigInt(`0x${slice}`);
}

function toNumber(value: bigint, what: string): number {
  if (value > BigInt(Number.MAX_SAFE_INTEGER)) throw new Error(`${what} is implausibly large: ${value}`);
  return Number(value);
}

/** `aggregate3((address,bool,bytes)[])` calldata for a list of calls, every one with allowFailure true. */
export function encodeAggregate3(calls: readonly {target: string; callData: string}[]): string {
  const tuples = calls.map((call) => {
    const data = hexBody(call.callData);
    const padding = "0".repeat((64 - (data.length % 64)) % 64);
    return (
      word(BigInt(call.target)) + word(1n) + word(0x60n) + word(BigInt(data.length / 2)) + data + padding
    );
  });
  // Offsets are measured from the first word after the array length.
  let cursor = 32 * tuples.length;
  const offsets: string[] = [];
  for (const tuple of tuples) {
    offsets.push(word(BigInt(cursor)));
    cursor += tuple.length / 2;
  }
  return `${AGGREGATE3}${word(0x20n)}${word(BigInt(tuples.length))}${offsets.join("")}${tuples.join("")}`;
}

export type AggregateItem = {success: boolean; returnData: string};

/** Decodes `Result[] (bool success, bytes returnData)`. */
export function decodeAggregate3(raw: string): AggregateItem[] {
  const body = hexBody(raw);
  const arrayAt = toNumber(wordAt(body, 0), "the aggregate3 array offset");
  const count = toNumber(wordAt(body, arrayAt), "the aggregate3 result count");
  const base = arrayAt + 32;
  const items: AggregateItem[] = [];
  for (let i = 0; i < count; i += 1) {
    const at = base + toNumber(wordAt(body, base + 32 * i), "an aggregate3 element offset");
    const success = wordAt(body, at);
    if (success > 1n) throw new Error(`aggregate3 element ${i} has a success flag of ${success}`);
    const dataAt = at + toNumber(wordAt(body, at + 32), "an aggregate3 returnData offset");
    const length = toNumber(wordAt(body, dataAt), "an aggregate3 returnData length");
    const data = body.slice((dataAt + 32) * 2, (dataAt + 32 + length) * 2);
    if (data.length !== length * 2) throw new Error(`aggregate3 element ${i} is truncated`);
    items.push({success: success === 1n, returnData: `0x${data}`});
  }
  return items;
}

