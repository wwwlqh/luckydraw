export function report(result: CheckResult, recordPath: string): string {
  const lines: string[] = [];
  for (const finding of result.findings) {
    const status = finding.level === "error" ? "FAIL" : finding.level === "note" ? "note" : "ok  ";
    lines.push(`${status}  ${finding.code}  ${finding.message}`);
  }
  lines.push("");
  if (result.fragment === null) {
    lines.push("No fragment: the chain did not answer the two facts the record holds.");
  } else if (result.ok) {
    lines.push(`Paste into ${recordPath}, replacing the whole "networkIdentity" object:`);
    lines.push("");
    lines.push(result.fragment);
    lines.push("");
    lines.push(
      'Set "source".url to the page the Multicall3 address came from, keep the date, then run ' +
        "`npx pnpm@12.3.4 validate:config`. This script does not write the file.",
    );
  } else {
    lines.push("Something above failed. The fragment is withheld; fix the failure and run this again.");
  }
  return lines.join("\n");
}

type Args = {rpcUrl: string; chainId: bigint; multicall3: string; configRoot: string; headSlack?: bigint};

export class UsageError extends Error {}

export const USAGE =
  "usage: node scripts/check_chain_record.ts --rpc-url <url> --chain-id <id> --multicall3 <address>\n" +
  "                                          [--config-root <dir>] [--head-slack <blocks>]";

export function parseArgs(argv: readonly string[]): Args {
  const values = new Map<string, string>();
  for (let i = 0; i < argv.length; i += 1) {
    const flag = argv[i];
    if (flag === "--write" || flag === "--fix" || flag === "--apply") {
      throw new UsageError(
        `${flag} is refused: this script is read-only. It prints the fragment and you paste it, so that ` +
          "no configuration record is ever changed by an endpoint's answer.",
      );
    }
    if (!flag.startsWith("--")) throw new UsageError(`unexpected argument ${JSON.stringify(flag)}`);
    const next = argv[i + 1];
    if (next === undefined || next.startsWith("--")) throw new UsageError(`${flag} needs a value`);
    values.set(flag, next);
    i += 1;
  }
  const required = (flag: string): string => {
    const value = values.get(flag);
    if (value === undefined || value.trim() === "") throw new UsageError(`${flag} is required`);
    return value.trim();
  };
  const rpcUrl = required("--rpc-url");
  if (!/^https?:\/\//.test(rpcUrl)) throw new UsageError("--rpc-url must be an http(s) URL");
  const chainIdText = required("--chain-id");
  if (!/^[0-9]+$/.test(chainIdText)) throw new UsageError("--chain-id must be a positive integer");
  const chainId = BigInt(chainIdText);
  if (chainId <= 0n) throw new UsageError("--chain-id must be a positive integer");
  const multicall3 = required("--multicall3");
  if (!ADDRESS_RE.test(multicall3)) {
    throw new UsageError("--multicall3 must be an 0x-prefixed 20-byte address");
  }
  const slackText = values.get("--head-slack");
  if (slackText !== undefined && !/^[0-9]+$/.test(slackText)) {
    throw new UsageError("--head-slack must be a non-negative integer");
  }
  return {
    rpcUrl,
    chainId,
    multicall3,
    configRoot: values.get("--config-root")?.trim() || join(REPO_ROOT, "config"),
    headSlack: slackText === undefined ? undefined : BigInt(slackText),
  };
}

/** Reads the two `networkIdentity` fields, or null when the record is absent. */
export function loadRecord(path: string): ChainRecordIdentity | null {
  let raw: string;
  try {
    raw = readFileSync(path, "utf8");
  } catch {
    return null;
  }
  const doc = JSON.parse(raw) as Record<string, unknown>;
  const identity = doc.networkIdentity;
  const field = (name: string): string | null => {
    if (identity === null || typeof identity !== "object") return null;
    const value = (identity as Record<string, unknown>)[name];
    return typeof value === "string" ? value : null;
  };
  return {
    chainId: typeof doc.chainId === "number" ? doc.chainId : null,
    genesisHash: field("genesisHash"),
    multicall3: field("multicall3"),
  };
}

async function main(): Promise<void> {
  let args: Args;
  try {
    args = parseArgs(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error instanceof UsageError ? error.message : String(error)}\n${USAGE}\n`);
    process.exitCode = 2;
    return;
  }
  const recordPath = resolve(args.configRoot, "chains", `${args.chainId}.json`);
  const display = `config/chains/${args.chainId}.json`;
  process.stdout.write(
    `Reading chain ${args.chainId} through <rpc>, Multicall3 at ${args.multicall3.toLowerCase()}.\n\n`,
  );
  const result = await checkChainRecord({
    chainId: args.chainId,
    multicall3: args.multicall3,
    rpc: httpRpc(args.rpcUrl),
    record: loadRecord(recordPath),
    recordPath: display,
    headSlack: args.headSlack,
  });
  process.stdout.write(`${report(result, display)}\n`);
  process.exitCode = result.ok ? 0 : 1;
}

if (process.argv[1] !== undefined && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await main();
}
